#pragma once

#include <stdint.h>

#include "types.h"

// Публикация согласованного снимка SystemState для читателей, живущих в
// другой задаче (AsyncWebServer/AsyncTCP). Запись состояния идёт из loop(),
// чтение снимка — из сетевых обработчиков, поэтому снимок защищён seqlock:
// читатель повторяет копирование, если во время него прошла публикация.
namespace StateSnapshot {

// Публикация текущего состояния. Вызывается из loop() с ограничением по
// времени (STATE_SNAPSHOT_INTERVAL_MS), а не на каждой итерации.
void publish(const SystemState &state);

// Согласованное копирование снимка. Возвращает false, если снимок ещё не
// публиковался или не удалось получить целостную копию за несколько попыток.
bool read(SystemState &out);

// Копия снимка, либо копия живого g_state, если снимок ещё не готов.
// Нужна как безопасный fallback на первых итерациях после старта.
void readOrLive(SystemState &out);

// Признак того, что хотя бы одна публикация уже произошла.
bool isReady();

// Номер последней публикации (чётный — снимок стабилен).
uint32_t sequence();

}  // namespace StateSnapshot